"""Regenerate the vendored Powerwall descriptor bundle with grpcio-tools==1.60.0.

Run in an isolated build environment; grpcio-tools is never a runtime dependency.
"""

from pathlib import Path
import subprocess
import sys
import tempfile

import grpc_tools


ROOT = Path(__file__).resolve().parents[1]
SCHEMAS = ROOT / "custom_components/power_sync/powerwall_local/energy_device"


def main() -> None:
    version = subprocess.check_output(
        [sys.executable, "-m", "grpc_tools.protoc", "--version"], text=True
    ).strip()
    if version != "libprotoc 25.0":
        raise SystemExit(f"Expected libprotoc 25.0 (grpcio-tools==1.60.0), got {version}")
    source = SCHEMAS / "proto"
    with tempfile.TemporaryDirectory() as directory:
        output = Path(directory) / "energy_device.desc"
        subprocess.run(
            [
                sys.executable, "-m", "grpc_tools.protoc",
                f"-I{source}",
                f"-I{Path(grpc_tools.__file__).parent / '_proto'}",
                "--include_imports", f"--descriptor_set_out={output}",
                *[str(path) for path in sorted(source.glob("*.proto"))],
            ],
            check=True,
        )
        (SCHEMAS / "_descriptors.py").write_text(
            '# Generated by scripts/build_powerwall_schemas.py; do not edit.\n'
            '# Source: tesla-protocol 1.4.0, protoc 25.0; see README.md.\n'
            f'FILE_DESCRIPTOR_SET = {output.read_bytes()!r}\n'
        )


if __name__ == "__main__":
    main()
